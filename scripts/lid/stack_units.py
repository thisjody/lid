#!/usr/bin/env python3
"""Render the ToolHive systemd user units from stack/stack.yaml (ADR 26-11-03-002). Runs on the build box.

  stack_units.py STACK_YAML OUT_DIR   -> writes thv-<name>.service (+ <name>.profile.json) into OUT_DIR,
                                         prints one line per server: name port unit secret|-
  stack_units.py STACK_YAML get PATH  -> prints one value (dotted path, e.g. components.toolhive.pin.tag)
  stack_units.py STACK_YAML render-agw CONFIG -> the agentgateway config with host.internal_ip filled in
(stack/site.yaml, when present, is merged over the manifest: stack_site.py)
"""
import json, os, sys, yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from stack_site import agw_config, load  # noqa: E402

m = load(sys.argv[1])
comp = {c['name']: c for c in m['components']}

if sys.argv[2] == 'get':
    # A missing key fails (exit 1); `--optional` prints nothing for it instead. A null prints nothing; a list prints its
    # items space-separated (never "None" or "True" as a value: review finding F11).
    v = {'host': m['host'], 'components': comp}
    try:
        for k in sys.argv[3].split('.'):
            v = v[k]
    except (KeyError, TypeError):
        if '--optional' in sys.argv[4:]:
            sys.exit(0)
        sys.exit('stack_units: no %s in the manifest or site.yaml' % sys.argv[3])
    if isinstance(v, bool):
        v = 'true' if v else 'false'
    if v is None:
        if '--optional' in sys.argv[4:]:
            sys.exit(0)
        sys.exit('stack_units: %s is null in the manifest or site.yaml' % sys.argv[3])
    print(' '.join(map(str, v)) if isinstance(v, list) else v)
    sys.exit(0)

if sys.argv[2] == 'render-agw':
    sys.stdout.write(agw_config(m, sys.argv[3]))
    sys.exit(0)

out = sys.argv[2]
# The egress proxy thv starts for --isolate-network: pinned by release tag + digest (thv's own default is :latest, which
# Stacklok rebuilds from alpine edge; 11/17 the rebuilt box got an unreviewed build). thv reads TOOLHIVE_EGRESS_IMAGE (squid.go).
eg = comp['toolhive'].get('egress_image')
egress_env = ('Environment=TOOLHIVE_EGRESS_IMAGE=%s\n' % eg) if eg else ''
ip = comp['toolhive'].get('bind') or m['host']['internal_ip']   # loopback since ADR 26-11-03-004
home = os.path.expanduser('~')
for s in comp['toolhive']['servers']:
    n = s['name']
    prof = s['permission_profile']
    if isinstance(prof, dict):
        p = os.path.join(home, 'stack', 'profiles', n + '.json')
        open(os.path.join(out, n + '.profile.json'), 'w').write(json.dumps(prof, indent=1) + '\n')
        prof = p
    run = ['%h/.local/bin/thv', 'run', '--foreground', '--name', n, '--transport', s['transport'], '--host', ip, '--proxy-port', str(s['port']),
           '--permission-profile', prof, '--isolate-network=%s' % ('true' if s['isolate_network'] else 'false')]
    for k, v in (s.get('env') or {}).items():
        run += ['-e', '%s=%s' % (k, v)]
    if s.get('secret'):
        run += ['--secret', '%s,target=%s' % (s['secret'], s['secret_env'])]
    run.append('%s@%s' % (s['image'], s['digest']))
    unit = f"""# Generated by scripts/lid/stack_up.sh from stack/stack.yaml. Do not edit on the box (ADR 26-11-03-001).
[Unit]
Description=ToolHive MCP server {n} on {ip}:{s['port']} (ADR 26-11-03-002)
Requires=podman.socket
After=podman.socket network-online.target

[Service]
Environment=XDG_RUNTIME_DIR=%t TOOLHIVE_PODMAN_SOCKET=%t/podman/podman.sock
{egress_env}ExecStartPre=%h/stack/bin/thv_prime.sh
ExecStartPre=-%h/.local/bin/thv rm {n}
ExecStart={' '.join(run)}
ExecStop=-%h/.local/bin/thv stop {n}
Restart=on-failure
RestartSec=15

[Install]
WantedBy=default.target
"""
    open(os.path.join(out, s['unit']), 'w').write(unit)
    print(n, s['port'], s['unit'], s.get('secret') or '-')
